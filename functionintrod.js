//FUNCTION INTRODUCTION
function greet() {
    console.log("hello world")
}
//just defining the function, not calling it yet.

//function parameter
function greet(name) {
    console.log("hello world" + name)
}
//just defining the function parameter, not calling it yet.

//FUNCTION RETURN VALUE
function greet(a, b) {
    return a + b;
}
//just defining the function return value, not calling it yet.

//FUNCTION EXPRESSION
let greet = function() {
    console.log("hello world")
}
//just defining the function expression value storage, not calling it yet.

//ARROW FUNCTION
let greet = () => {
    console.log("hello world")
}
//Short/simple function syntax కోసం.